function m = local_name_map()
% Two column cell array: PTB unified name, ImGuiKey name.
    letters = cell(26, 2);
    for i = 1:26
        letters{i, 1} = char('a' + i - 1);
        letters{i, 2} = ['ImGuiKey_' upper(char('a' + i - 1))];
    end
    digits = {'1!', 'ImGuiKey_1'; '2@', 'ImGuiKey_2'; '3#', 'ImGuiKey_3'; ...
              '4$', 'ImGuiKey_4'; '5%', 'ImGuiKey_5'; '6^', 'ImGuiKey_6'; ...
              '7&', 'ImGuiKey_7'; '8*', 'ImGuiKey_8'; '9(', 'ImGuiKey_9'; ...
              '0)', 'ImGuiKey_0'};
    fkeys = cell(24, 2);
    for i = 1:24
        fkeys{i, 1} = sprintf('F%d', i);
        fkeys{i, 2} = sprintf('ImGuiKey_F%d', i);
    end
    keypadDigits = cell(10, 2);
    for i = 0:9
        keypadDigits{i + 1, 1} = sprintf('%d', i);
        keypadDigits{i + 1, 2} = sprintf('ImGuiKey_Keypad%d', i);
    end

    % PTB calls USB-HID usage 42 "DELETE", which is the Backspace key, while
    % the Windows and Linux tables use "DELETE" for the forward delete key.
    if ismac
        deleteKey = 'ImGuiKey_Backspace';
    else
        deleteKey = 'ImGuiKey_Delete';
    end

    rest = { ...
        'Return', 'ImGuiKey_Enter'; 'ENTER', 'ImGuiKey_KeypadEnter'; ...
        'ESCAPE', 'ImGuiKey_Escape'; 'esc', 'ImGuiKey_Escape'; ...
        'DELETE', deleteKey; 'BackSpace', 'ImGuiKey_Backspace'; ...
        'backspace', 'ImGuiKey_Backspace'; 'DeleteForward', 'ImGuiKey_Delete'; ...
        'tab', 'ImGuiKey_Tab'; 'space', 'ImGuiKey_Space'; ...
        '-_', 'ImGuiKey_Minus'; '=+', 'ImGuiKey_Equal'; ...
        '[{', 'ImGuiKey_LeftBracket'; ']}', 'ImGuiKey_RightBracket'; ...
        '[', 'ImGuiKey_LeftBracket'; ']', 'ImGuiKey_RightBracket'; ...
        '\|', 'ImGuiKey_Backslash'; '\\', 'ImGuiKey_Backslash'; ...
        ';:', 'ImGuiKey_Semicolon'; ';', 'ImGuiKey_Semicolon'; ...
        '''"', 'ImGuiKey_Apostrophe'; '''', 'ImGuiKey_Apostrophe'; ...
        '`~', 'ImGuiKey_GraveAccent'; '`', 'ImGuiKey_GraveAccent'; ...
        ',<', 'ImGuiKey_Comma'; '.>', 'ImGuiKey_Period'; '/?', 'ImGuiKey_Slash'; ...
        'CapsLock', 'ImGuiKey_CapsLock'; 'capslock', 'ImGuiKey_CapsLock'; ...
        'PrintScreen', 'ImGuiKey_PrintScreen'; 'ScrollLock', 'ImGuiKey_ScrollLock'; ...
        'scrolllock', 'ImGuiKey_ScrollLock'; 'Pause', 'ImGuiKey_Pause'; ...
        'Insert', 'ImGuiKey_Insert'; 'insert', 'ImGuiKey_Insert'; ...
        'Home', 'ImGuiKey_Home'; 'home', 'ImGuiKey_Home'; ...
        'PageUp', 'ImGuiKey_PageUp'; 'pageup', 'ImGuiKey_PageUp'; ...
        'End', 'ImGuiKey_End'; 'end', 'ImGuiKey_End'; ...
        'PageDown', 'ImGuiKey_PageDown'; 'pagedown', 'ImGuiKey_PageDown'; ...
        'RightArrow', 'ImGuiKey_RightArrow'; 'LeftArrow', 'ImGuiKey_LeftArrow'; ...
        'DownArrow', 'ImGuiKey_DownArrow'; 'UpArrow', 'ImGuiKey_UpArrow'; ...
        'right', 'ImGuiKey_RightArrow'; 'left', 'ImGuiKey_LeftArrow'; ...
        'down', 'ImGuiKey_DownArrow'; 'up', 'ImGuiKey_UpArrow'; ...
        'NumLockClear', 'ImGuiKey_NumLock'; 'NumLock', 'ImGuiKey_NumLock'; ...
        'numlock', 'ImGuiKey_NumLock'; ...
        '/', 'ImGuiKey_KeypadDivide'; '*', 'ImGuiKey_KeypadMultiply'; ...
        '-', 'ImGuiKey_KeypadSubtract'; '+', 'ImGuiKey_KeypadAdd'; ...
        '.', 'ImGuiKey_KeypadDecimal'; '=', 'ImGuiKey_KeypadEqual'; ...
        'Application', 'ImGuiKey_Menu'; 'Menu', 'ImGuiKey_Menu'; ...
        'applications', 'ImGuiKey_Menu'; ...
        'LeftControl', 'ImGuiKey_LeftCtrl'; 'RightControl', 'ImGuiKey_RightCtrl'; ...
        'left_control', 'ImGuiKey_LeftCtrl'; 'right_control', 'ImGuiKey_RightCtrl'; ...
        'LeftShift', 'ImGuiKey_LeftShift'; 'RightShift', 'ImGuiKey_RightShift'; ...
        'left_shift', 'ImGuiKey_LeftShift'; 'right_shift', 'ImGuiKey_RightShift'; ...
        'LeftAlt', 'ImGuiKey_LeftAlt'; 'RightAlt', 'ImGuiKey_RightAlt'; ...
        'LeftGUI', 'ImGuiKey_LeftSuper'; 'RightGUI', 'ImGuiKey_RightSuper'; ...
        'Shift', 'ImGuiKey_LeftShift'; 'shift', 'ImGuiKey_LeftShift'; ...
        'control', 'ImGuiKey_LeftCtrl'; 'alt', 'ImGuiKey_LeftAlt'};

    m = [letters; digits; fkeys; keypadDigits; rest];
end

function key = local_lookup(nameMap, n)
    key = '';
    for i = 1:size(nameMap, 1)
        if strcmp(nameMap{i, 1}, n)
            key = nameMap{i, 2};
            return;
        end
    end
end
