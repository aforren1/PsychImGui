function map = PsychImGuiKeymap()
% PsychImGuiKeymap  Build the PTB keycode to ImGuiKey table.
%
%   map = PsychImGuiKeymap() returns int32(256,1). Entry k holds the ImGuiKey
%   value for PTB keycode k, or 0 when the key has no Dear ImGui equivalent.
%   Pass the result to PsychImGui('Init', win, rect, map).
%
%   Psychtoolbox owns the per-platform keycode differences, so the table is
%   built from KbName('UnifyKeyNames') rather than from a table per operating
%   system inside the MEX. When Psychtoolbox is absent the function falls back
%   to the USB-HID name table that UnifyKeyNames itself targets, so the binding
%   and its tests still run.
%
%   See also PsychImGui, PsychImGuiInput.

    names = local_key_names();
    imKeys = PsychImGui('Enum');

    nameMap = local_name_map();
    map = zeros(256, 1, 'int32');
    for k = 1:256
        n = names{k};
        if isempty(n)
            continue;
        end
        key = local_lookup(nameMap, n);
        if isempty(key)
            continue;
        end
        if isfield(imKeys, key)
            map(k) = int32(imKeys.(key));
        end
    end
end

