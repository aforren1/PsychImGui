    if exist('KbName', 'file')
        KbName('UnifyKeyNames');
        for k = 1:256
            try
                n = KbName(k);
            catch
                n = '';
            end
            if ischar(n)
                names{k} = n;
            elseif iscell(n) && ~isempty(n) && ischar(n{1})
                names{k} = n{1};
